import { createHash } from "node:crypto";
import type { Plugin } from "vite";

// Offline (backlog 1.7): a service worker written at build time with the list of every file the build makes, so the
// whole application — the GS1 Barcode Syntax Engine's and ZXing's WebAssembly, the font, the EPC schemes — is kept by
// the browser on the first visit and works without a network afterwards. No library: the worker is a few lines.
// Pages are fetched from the network first (so a new release is seen at once) and from the cache when offline; every
// other file has a content hash in its name and is served from the cache first, whatever the request's headers (a
// server may answer "Vary: Origin", and a module script is asked for with an Origin). A release changes the list, hence the
// worker, which the browser then installs, deleting the previous release's files.

const PUBLIC_FILES = ["manifest.webmanifest", "icon.svg", "icon-192.png", "icon-512.png"];

const worker = (cache: string, files: string[]) => `// Generated by apps/web/offline.ts at build time.
const CACHE = ${JSON.stringify(cache)};
const FILES = ${JSON.stringify(files)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith("gs1-label-studio-") && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put("./", copy));
          return response;
        })
        .catch(() => caches.match("./")),
    );
    return;
  }
  event.respondWith(caches.match(request, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit ?? fetch(request)));
});
`;

export function offline(): Plugin {
  return {
    name: "gs1-label-studio-offline",
    apply: "build",
    generateBundle(_options, bundle) {
      const files = ["./", ...PUBLIC_FILES.map((f) => `./${f}`), ...Object.keys(bundle).sort().map((f) => `./${f}`)]
        .filter((f) => f !== "./index.html");
      const cache = `gs1-label-studio-${createHash("sha256").update(files.join("\n")).digest("hex").slice(0, 12)}`;
      this.emitFile({ type: "asset", fileName: "sw.js", source: worker(cache, files) });
    },
  };
}
