import { createHash } from "node:crypto";
import type { Plugin } from "vite";

// Offline (backlog 1.7): a service worker written at build time with the list of every file the build makes, so the
// whole application — the GS1 Barcode Syntax Engine's and ZXing's WebAssembly, the font, the EPC schemes — is kept by
// the browser on the first visit and works without a network afterwards. No library: the worker is a few lines.
// Pages are fetched from the network first (so a new release is seen at once) and from the cache when offline; every
// other file has a content hash in its name and is served from the cache first, whatever the request's headers (a
// server may answer "Vary: Origin", and a module script is asked for with an Origin). A release changes the list, hence the
// worker, which the browser then installs, deleting the previous release's files.
// Two sites share the origin (backlog 0.4, ADR 0010): the stable one at /<repository>/ and develop under
// /<repository>/develop/, inside the stable worker's scope. So each worker's caches are named after its base path and it
// deletes only its own; it answers a navigation only to its own page (the application is one page, its places after #),
// so that the stable worker never takes develop's page for its own; and it serves files from its own cache.

const PUBLIC_FILES = ["manifest.webmanifest", "icon.svg", "icon-192.png", "icon-512.png"];

const worker = (prefix: string, cache: string, files: string[], old: boolean) => `// Generated by apps/web/offline.ts at build time.
const PREFIX = ${JSON.stringify(prefix)};
const CACHE = ${JSON.stringify(cache)};
const FILES = ${JSON.stringify(files)};
const PAGE = new URL("./", self.location).pathname;
// Before backlog 0.4 the one site's caches were named gs1-label-studio-<hash>: the stable site's worker deletes them
const OLD = ${old ? "/^gs1-label-studio-[0-9a-f]{12}$/" : "/$^/"};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => (key.startsWith(PREFIX) || OLD.test(key)) && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === "navigate") {
    const path = new URL(request.url).pathname;
    if (path !== PAGE && path !== PAGE + "index.html") return; // another site's page, such as develop's
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put("./", copy));
          return response;
        })
        .catch(() => caches.open(CACHE).then((cache) => cache.match("./"))),
    );
    return;
  }
  event.respondWith(
    caches.open(CACHE)
      .then((cache) => cache.match(request, { ignoreSearch: true, ignoreVary: true }))
      .then((hit) => hit ?? fetch(request)),
  );
});
`;

/** The prefix of the caches of the site at `base` ("/gs1-label-studio/", "/gs1-label-studio/develop/"). */
export function cachePrefix(base: string): string {
  return `gs1-label-studio ${base} `;
}

/** The service worker's plugin; `stable` for the stable site's, which also deletes the caches of before ADR 0010. */
export function offline({ stable = true }: { stable?: boolean } = {}): Plugin {
  let base = "/";
  return {
    name: "gs1-label-studio-offline",
    apply: "build",
    configResolved(config) {
      base = config.base;
    },
    generateBundle(_options, bundle) {
      // A bundle's file may replace a public one (develop's manifest): each listed once, as the Cache API requires
      const files = [...new Set(["./", ...PUBLIC_FILES.map((f) => `./${f}`), ...Object.keys(bundle).sort().map((f) => `./${f}`)])]
        .filter((f) => f !== "./index.html");
      const prefix = cachePrefix(base);
      const cache = `${prefix}${createHash("sha256").update(files.join("\n")).digest("hex").slice(0, 12)}`;
      this.emitFile({ type: "asset", fileName: "sw.js", source: worker(prefix, cache, files, stable) });
    },
  };
}
